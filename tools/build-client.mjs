import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(await fs.readFile(path.join(root, 'client-release.json'), 'utf8'));
if (source.repository !== 'https://github.com/guenoh/pokesurvivor-kor.git' || !/^[a-f0-9]{40}$/.test(source.commit)) throw new Error('Invalid pinned client release');
const client = path.join(root, '.build', 'client');
await fs.rm(client, { recursive: true, force: true });
await fs.mkdir(client, { recursive: true });
const run = (command, args) => execFileSync(command, args, { cwd: client, stdio: 'inherit' });
run('git', ['init', '--quiet']);
run('git', ['fetch', '--depth=1', source.repository, source.commit]);
run('git', ['checkout', '--detach', 'FETCH_HEAD']);
const compatibility = await fs.readFile(path.join(client, 'kor/retired-content.js'));
if (!compatibility.equals(await fs.readFile(path.join(root, 'src/retired-content.cjs')))) throw new Error('Retired content compatibility must match the pinned client');
const growth = await fs.readFile(path.join(client, 'kor/duplicate-growth.js'));
if (!growth.equals(await fs.readFile(path.join(root, 'src/duplicate-growth.cjs')))) throw new Error('Duplicate growth policy must match the pinned client');
if (!(await fs.readFile(path.join(client,'js/systems/gacha.js'))).equals(await fs.readFile(path.join(root,'data/upstream-gacha.js')))) throw new Error('Server draw engine must match the preserved upstream engine');
const catalogueTool = path.join(client,'kor/gacha-catalog.cjs');
const generated = execFileSync(process.execPath, ['-e', 'process.stdout.write(JSON.stringify(require(process.argv[1]).catalogue()))', catalogueTool], { encoding:'utf8' });
if (generated !== (await fs.readFile(path.join(root,'data/gacha-catalog.json'),'utf8')).trim()) throw new Error('Server catalogue must match the pinned client');
const config = JSON.parse(await fs.readFile(path.join(root, 'config/notices.json'), 'utf8'));
const dbSource = await fs.readFile(path.join(client, 'js/core/db.js'), 'utf8');
const startingCoins = dbSource.match(/\bconst START_COINS\s*=\s*(\d+)\s*;/);
if (!startingCoins || Number(startingCoins[1]) !== config.newAccountCoins) throw new Error('Member-gift starting coins do not match the pinned original game');
run('pnpm', ['install', '--frozen-lockfile', '--ignore-scripts', '--prod=false']);
const tests = (await fs.readdir(path.join(client, 'tests'))).filter(name => name.endsWith('.test.cjs')).sort().map(name => `tests/${name}`);
if (tests.length === 0) throw new Error('Pinned client has no tests');
run(process.execPath, ['--test', ...tests]);
run(process.execPath, ['tools/build.js', '--sin-seo']);
run(process.execPath, ['kor/package.cjs']);
await fs.rm(path.join(root, 'public'), { recursive: true, force: true });
await fs.cp(path.join(client, 'dist'), path.join(root, 'public'), { recursive: true });
const serverCommit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
await fs.writeFile(path.join(root, 'public', 'release.json'), JSON.stringify({ client: source.commit, server: serverCommit }) + '\n');
console.log(`Packaged Korean client ${source.commit}`);
